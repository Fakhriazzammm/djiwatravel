/** Framing box for an ISO 3166-1 alpha-2 code (any case), or null when the code is not a country. */
export function countryBoundsFor(code: string | null | undefined): CountryBounds | null {
  const key = (code ?? "").trim().toUpperCase();
  return Object.prototype.hasOwnProperty.call(COUNTRY_BOUNDS, key) ? COUNTRY_BOUNDS[key]! : null;
}

