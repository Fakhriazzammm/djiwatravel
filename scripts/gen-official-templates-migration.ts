/**
 * Generates migrations/088_travo_official_templates.sql from src/lib/official-templates.ts.
 * Covers come from Wikipedia lead images (wikimedia hosts only) and are cached in
 * scripts/official-template-covers.json so the SQL is reproducible offline.
 *   npx tsx scripts/gen-official-templates-migration.ts
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import {
  OFFICIAL_OWNER_NAME,
  OFFICIAL_OWNER_SUBJECT,
  officialTemplates,
} from "../src/lib/official-templates";

const COVER_PAGE: Record<string, string> = {
  JP: "Kyoto",
  KR: "Seoul",
  TH: "Bangkok",
  SG: "Marina Bay Sands",
  MY: "Kuala Lumpur",
  HK: "Victoria Peak",
  TW: "Taipei",
  VN: "Hanoi",
  TR: "Istanbul",
  AE: "Dubai",
  AU: "Sydney",
  IT: "Rome",
};
const cacheFile = new URL("./official-template-covers.json", import.meta.url);
const covers: Record<string, string> = existsSync(cacheFile)
  ? JSON.parse(readFileSync(cacheFile, "utf8"))
  : {};

async function lead(title: string): Promise<string | null> {
  const url = new URL("https://en.wikipedia.org/w/api.php");
  url.search = new URLSearchParams({
    action: "query",
    format: "json",
    titles: title,
    redirects: "1",
    prop: "pageimages",
    piprop: "thumbnail",
    pithumbsize: "900",
  }).toString();
  const res = await fetch(url, {
    headers: { "User-Agent": "DjiwaTravel/1.0 (https://djiwatravel.com)" },
  });
  const json = (await res.json()) as {
    query?: { pages?: Record<string, { thumbnail?: { source?: string } }> };
  };
  const src =
    (Object.values(json.query?.pages ?? {})[0]?.thumbnail?.source ?? "").split("?")[0] || null;
  return src &&
    ["upload.wikimedia.org", "thumb.wikimedia.org"].includes(new URL(src).hostname) &&
    src.length <= 500
    ? src
    : null;
}

for (const t of officialTemplates) {
  if (!covers[t.code]) {
    const found = await lead(COVER_PAGE[t.code] ?? t.country);
    if (found) covers[t.code] = found;
  }
}
writeFileSync(cacheFile, JSON.stringify(covers, null, 2) + "\n");

const q = (v: string | null) => (v === null ? "null" : `'${v.replace(/'/g, "''")}'`);
const parts: string[] = [
  "-- 088_travo_official_templates.sql",
  "-- GENERATED by scripts/gen-official-templates-migration.ts from src/lib/official-templates.ts.",
  "-- Official itinerary templates written by Travo (source = 'travo', owner = travo-official).",
  "-- Idempotent: a template is inserted once per slug and never overwritten, so Admin edits",
  "-- (hide, feature, delete) stick. Deleted ones are not re-created because this file runs once.",
  "",
  "BEGIN;",
  "",
];
for (const t of officialTemplates) {
  const rows = t.days.flatMap((day, d) =>
    day.map(
      ([start, title, location, category], i) =>
        `(${d + 1},${i},${q(start)}::time,${q(title)},${q(location)},${q(category)})`,
    ),
  );
  parts.push(
    `with t as (
  insert into trip_templates (slug,owner_subject,owner_name,title,description,destination_code,destination_name,day_count,cover_url,status,featured,source,published_at)
  values (${q(t.slug)},${q(OFFICIAL_OWNER_SUBJECT)},${q(OFFICIAL_OWNER_NAME)},${q(t.title)},${q(t.description)},${q(t.code)},${q(t.country)},${t.days.length},${q(covers[t.code] ?? null)},'published',${t.featured ? "true" : "false"},'travo',now())
  on conflict (slug) do nothing
  returning id
)
insert into trip_template_items (template_id,day_index,sort_order,start_time,title,location,category)
select t.id, v.day_index, v.sort_order, v.start_time, v.title, v.location, v.category
  from t, (values
    ${rows.join(",\n    ")}
  ) as v(day_index,sort_order,start_time,title,location,category);
`,
  );
}
parts.push("COMMIT;", "");
writeFileSync(
  new URL("../migrations/088_travo_official_templates.sql", import.meta.url),
  parts.join("\n"),
);
console.log(`templates: ${officialTemplates.length}, covers: ${Object.keys(covers).length}`);
